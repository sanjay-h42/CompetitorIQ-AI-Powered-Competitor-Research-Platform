from datetime import datetime, timezone
from typing import Dict, Any, List
from app.schemas.ai import ResearchReportSchema, CompetitorAnalysisSchema


def generate_markdown_report(
    report_data: ResearchReportSchema,
    analyses: List[CompetitorAnalysisSchema],
    project_info: Dict[str, Any]
) -> str:
    """
    Renders a comprehensive, publication-ready Markdown research report with
    citations, comparison tables, SWOT analyses, and explicit limitation disclosures.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: List[str] = []

    lines.append(f"# {report_data.title}")
    lines.append(f"**Target Company**: {project_info.get('company_name', 'Client Company')} ({project_info.get('website_url', '')})  ")
    lines.append(f"**Industry**: {project_info.get('industry', 'Technology')} | **Target Market**: {project_info.get('target_market', 'B2B')}  ")
    lines.append(f"**Generated by**: CompetitorIQ Autonomous Intelligence Engine  ")
    lines.append(f"**Research Date**: {now_str}\n")
    lines.append("---\n")

    # Executive Summary
    lines.append("## 1. Executive Summary\n")
    lines.append(report_data.executive_summary)
    lines.append("\n")

    # Research Methodology
    lines.append("## 2. Research Methodology & Compliance Bounds\n")
    lines.append(report_data.methodology)
    lines.append("\n")

    # Feature Comparison Matrix
    lines.append("## 3. Competitive Feature Comparison Matrix\n")
    if report_data.comparison_matrix:
        # Determine all competitor columns
        comp_names = set()
        for row in report_data.comparison_matrix:
            for cname in row.competitor_statuses.keys():
                comp_names.add(cname)
        sorted_comps = sorted(list(comp_names))

        headers = ["Capability / Feature", f"**{project_info.get('company_name')}**"] + [f"**{c}**" for c in sorted_comps]
        lines.append("| " + " | ".join(headers) + " |")
        lines.append("| " + " | ".join(["---"] * len(headers)) + " |")

        for row in report_data.comparison_matrix:
            row_cols = [row.feature_name, row.user_company_status]
            for c in sorted_comps:
                status = row.competitor_statuses.get(c, "Not publicly verified")
                row_cols.append(status)
            lines.append("| " + " | ".join(row_cols) + " |")
        lines.append("\n")

    # Pricing & Packaging
    lines.append("## 4. Pricing & Packaging Analysis\n")
    if report_data.pricing_comparison:
        lines.append("| Competitor | Pricing Model | Public Tiers Observed |")
        lines.append("| --- | --- | --- |")
        for p in report_data.pricing_comparison:
            lines.append(f"| **{p.get('competitor')}** | {p.get('model')} | {p.get('summary')} |")
        lines.append("\n")

    # Positioning Matrix
    lines.append("## 5. Market Positioning Matrix\n")
    if report_data.positioning_matrix:
        lines.append("| Company | Target Audience | Core Focus | Publicly Observed Strengths | Potential Gaps |")
        lines.append("| --- | --- | --- | --- | --- |")
        for pos in report_data.positioning_matrix:
            lines.append(
                f"| **{pos.company_name}** | {pos.target_audience} | {pos.core_focus} | "
                f"{pos.notable_strengths} | {pos.potential_limitations} |"
            )
        lines.append("\n")

    # Detailed Competitor Profiles
    lines.append("## 6. In-Depth Competitor Profiles\n")
    for idx, a in enumerate(analyses, 1):
        lines.append(f"### 6.{idx} {a.company_name}")
        lines.append(f"- **Website**: [{a.website_url}]({a.website_url})")
        lines.append(f"- **Pricing Model**: {a.pricing_model}")
        lines.append(f"- **Overview**: {a.overview}\n")

        lines.append("#### Publicly Listed Products & Key Features")
        for f in a.key_features[:6]:
            lines.append(f"- {f}")
        lines.append("\n")

        lines.append("#### Observable Strengths")
        for s in a.strengths[:4]:
            lines.append(f"- {s}")
        lines.append("\n")

        lines.append("#### Potential Inferred Weaknesses & Limitations")
        for w in a.weaknesses[:4]:
            lines.append(f"- {w}")
        lines.append("\n")

        if a.evidence_quotes:
            lines.append("#### Verifiable Citations & Source Excerpts")
            for q in a.evidence_quotes[:4]:
                lines.append(f"> \"{q.excerpt}\"\n> — *Source: [{q.source_url}]({q.source_url}) ({q.claim})*\n")

    # Market Gaps & Opportunities
    lines.append("## 7. Market Gaps & Differentiation Opportunities\n")
    lines.append("### Unmet Market Needs (Gaps)")
    for gap in report_data.market_gaps:
        lines.append(f"- {gap}")
    lines.append("\n### Strategic Opportunities")
    for opp in report_data.opportunities:
        lines.append(f"- {opp}")
    lines.append("\n### Competitive Risks")
    for risk in report_data.risks:
        lines.append(f"- {risk}")
    lines.append("\n")

    # Actionable Strategic Recommendations
    lines.append("## 8. Actionable Strategic Recommendations\n")
    for rec in report_data.strategic_recommendations:
        lines.append(f"- {rec}")
    lines.append("\n")

    # Limitations & Compliance Notice
    lines.append("## 9. Limitations & Compliance Statement\n")
    for lim in report_data.research_limitations:
        lines.append(f"- {lim}")
    lines.append("\n*Notice: All information retrieved strictly from publicly accessible endpoints. No paywalls, CAPTCHAs, or private credentials were bypassed.*")

    return "\n".join(lines)
